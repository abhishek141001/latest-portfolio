import fs from 'node:fs'
import ts from 'typescript'
const plan = JSON.parse(fs.readFileSync('data/article-plan.json', 'utf8'))
const order = new Map(plan.map((entry, index) => [entry.slug, index]))
const files = fs.readdirSync('data/articles').filter(name => name.endsWith('.json')).sort((a, b) => (order.get(a.slice(0, -5)) ?? Infinity) - (order.get(b.slice(0, -5)) ?? Infinity))
const imports = files.map((file, i) => `import article${i} from "./articles/${file}"`).join('\n')
const entries = files.map((_, i) => `article${i}`).join(', ')
fs.writeFileSync('data/researched-articles.ts', `// Generated by scripts/generate-article-index.mjs; edit individual article JSON files.\nimport type { Blog } from "@/lib/blog-types"\n${imports}\n\nconst drafts = [${entries}]\nexport const researchedArticles: Blog[] = drafts.map((draft) => ({\n  ...draft,\n  format: "Deep dive",\n  aiAssisted: true,\n  readTime: \x60\x24{Math.ceil(draft.content.trim().split(/\\s+/).length / 220)} min read\x60,\n  author: { name: "Abhishek Raj", bio: "Software developer writing about AI engineering and production software." },\n}))\n`)
console.log(`Indexed ${files.length} researched articles`)

// Social cards only need titles, so their edge bundle must not import article bodies.
const catalog = ts.createSourceFile('data/blogs.ts', fs.readFileSync('data/blogs.ts', 'utf8'), ts.ScriptTarget.Latest, true)
const social = []
for (const statement of catalog.statements) {
  if (!ts.isVariableStatement(statement)) continue
  for (const declaration of statement.declarationList.declarations) {
    if (declaration.name.getText(catalog) !== 'existingBlogs' || !declaration.initializer || !ts.isArrayLiteralExpression(declaration.initializer)) continue
    for (const article of declaration.initializer.elements) {
      if (!ts.isObjectLiteralExpression(article)) continue
      const values = Object.fromEntries(article.properties.filter(property => ts.isPropertyAssignment(property) && ts.isStringLiteralLike(property.initializer)).map(property => [property.name.getText(catalog), property.initializer.text]))
      if (!values.slug || !values.title) throw new Error('An existing blog needs a literal slug and title for its social card')
      social.push({ slug: values.slug, title: values.title })
    }
  }
}
if (!social.length) throw new Error('No existing articles found for social cards')
for (const file of files) {
  const article = JSON.parse(fs.readFileSync(`data/articles/${file}`, 'utf8'))
  social.push({ slug: article.slug, title: article.title })
}
fs.writeFileSync('data/blog-social.json', JSON.stringify(social, null, 2) + '\n')
